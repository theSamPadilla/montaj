#!/usr/bin/env python3
"""Rig a 3D model (.glb) on Tripo: add a skeleton so it can be animated.

Standalone, like generate_model. A model generated by generate_model is sent to
Tripo as the task that made it (its `<model>.tripo.json` record); any other .glb
is uploaded. Tripo's free riggability check runs first: a model it calls not
riggable fails with `not_riggable` and nothing is spent. The rig type is the
check's recommendation unless --rig-type is given. biped is rigged with Mixamo
bone names; every other type with Tripo's own.

--task-id collects a rig task already submitted (a run that stopped or ran out
of time names it, with its --rig-type): no new task, no new charge, and no
--model needed. Give --rig-type with it so animate_model can tell which rig the
file has. From the CLI, running the same command again with the same --out also
re-attaches to the task recorded in `<out>.tripo.json`. A model the check calls
avian is refused unless --rig-type avian is given: Tripo has no preset
animations for it. Animate the result with animate_model.
"""
import sys, os, argparse, json

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "lib"))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import fail, require_file
from connectors import ConnectorError, tripo
from _fail_reasons import fail_for


def main():
    p = argparse.ArgumentParser(description="Rig a 3D model (.glb) on Tripo")
    p.add_argument("--model", help="The .glb to rig. Required unless --task-id.")
    p.add_argument("--out", required=True)
    p.add_argument("--rig-type", dest="rig_type", choices=list(tripo.RIG_TYPES),
                   help="Skeleton type. Default: the one Tripo's free check recommends.")
    p.add_argument("--task-id", dest="task_id",
                   help="A rig task already submitted: wait for it and download it (no new charge).")
    p.add_argument("--json", action="store_true", help="Emit full JSON envelope")
    args = p.parse_args()

    if os.path.lexists(args.out):
        fail("invalid_out", f"{args.out} already exists. Montaj does not overwrite a model: choose a new --out.")
    if not args.out.lower().endswith(".glb"):
        fail("invalid_out", f"Tripo models are GLB files: --out must end in .glb, got {args.out!r}")

    if not args.task_id:
        if not args.model:
            fail("invalid_args", "--model is required (unless --task-id collects a rig task already submitted)")
        require_file(args.model)
        if not args.model.lower().endswith(".glb"):
            fail("invalid_args", f"--model must be a .glb file, got {args.model!r}")

    try:
        if args.task_id:
            result = tripo.resume_rig(args.task_id, args.out, rig_type=args.rig_type)
        else:
            result = tripo.rig_model(model_path=args.model, out_path=args.out, rig_type=args.rig_type)
    except tripo.NotRiggable as e:
        fail("not_riggable", str(e))
    except tripo.UnsupportedModel as e:
        fail("unsupported_model", str(e))
    except tripo.InvalidInput as e:
        fail("invalid_args", str(e))
    except ConnectorError as e:
        fail_for(e, "Tripo")

    if args.json:
        print(json.dumps(result))
    else:
        print(result["path"])


if __name__ == "__main__":
    main()
