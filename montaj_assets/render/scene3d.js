/**
 * scene3d.js (§239): a 3D scene item is an overlay item whose `src` is the reserved `engine:scene3d`:
 *
 *   { "type": "overlay", "src": "engine:scene3d", "start": 12, "end": 16.5,
 *     "props": { "scene": "hands", "inPoint": 2 } }
 *
 * `materializeScene3d` turns each one into the plain overlay every other part of the render already knows, in
 * place and before anything else reads the project: `src` becomes the stage the HOST supplies
 * (`MONTAJ_SCENE3D_STAGE`, an absolute path to a stage .jsx: the app keeps the freshest one in its runtime home),
 * and `props` gain `sceneFile` (the scene's active.json, an absolute path: it travels to the page as a file URL and is
 * what the sample cache's manifest records), `sceneJson` (that file's text, read and checked here, so the stage draws from
 * the page's first render and an unreadable scene fails the render instead of drawing blank; one string, so the
 * props scanners (path rewriting, the read boundary, named URLs) see one value and not every string of the scene) and `inPoint` (seconds
 * into the scene's own timeline). From then on the bundle, the read boundary,
 * the sample cache's input manifest (it records props file paths, so an edited scene misses) and the segment encoder
 * need to know nothing about scenes.
 *
 * `scene` names a folder under `<project>/models/scenes/<name>/`; absent is the project's single scene,
 * `<project>/models/active.json` (what the model-3d template's overlay copy imports today). A missing stage or scene
 * is an error that names it, never a blank frame. A second pass finds nothing left to do.
 *
 * 3D39: a scene's physics is a bake the app writes beside its file, `bake/<key>.mjbk` (key: the first 32 hex characters of
 * the sha256 of the scene file's bytes). When one exists for the file as it is now, `props.physicsBake` carries its bytes
 * as base64 and the stage plays it; else the stage plays keyed motion. The segment cache keys on the props, so a new bake
 * re-renders and an unchanged one reuses the chunks.
 */
import { createHash } from 'crypto'
import { closeSync, existsSync, lstatSync, openSync, readFileSync, readSync, statSync } from 'fs'
import { dirname, join, resolve } from 'path'
import { trackItems } from './project-tracks.js'

export const SCENE3D_SRC = 'engine:scene3d'
export const SCENE3D_STAGE_ENV = 'MONTAJ_SCENE3D_STAGE'
// The same rule save_model and the preview use (a folder made by hand with any other name would export and not preview).
const SCENE_NAME = /^[a-z0-9][a-z0-9-]{0,47}$/

/** An error with a stable `code`, for the CLI's JSON failure line. */
export class Scene3dError extends Error {
  constructor(code, message) {
    super(message)
    this.code = code
  }
}

export const isScene3dItem = (item) => !!item && item.type === 'overlay' && item.src === SCENE3D_SRC

/**
 * The first line of every 3D stage the app generates (its build-model3d-stage.mjs): the stage of a scene item, and the
 * per-project stage an older project placed as a plain overlay (`overlays/model3d_stage.jsx` and its kin).
 */
export const STAGE_BUNDLE_HEAD = '// GENERATED by library/scripts/build-model3d-stage.mjs'
// The head is all that is read: a stage is about 200 KB.
const HEAD_BYTES = 300

/** The first `bytes` of a file as text, or null when it cannot be read. */
function readHead(path, bytes) {
  let fd
  try {
    fd = openSync(path, 'r')
    const buf = Buffer.alloc(bytes)
    return buf.toString('utf8', 0, readSync(fd, buf, 0, bytes, 0))
  } catch {
    return null
  } finally {
    if (fd !== undefined) closeSync(fd)
  }
}

/**
 * Whether an overlay item draws a 3D stage (§377): a scene item (`engine:scene3d`), before or after
 * materializeScene3d points it at the host's stage (`componentPath` is then that stage), or an overlay whose source is
 * a generated stage (STAGE_BUNDLE_HEAD), as an older project's per-project stage is. Its render spec carries
 * `scene3d: true`, and its motion blur is averaged in the page (renderer.js blursInPage). A source that is missing or
 * cannot be read is not a stage.
 *
 * @param {object} item
 * @param {string} componentPath  the overlay's source, as render.js resolves it
 */
export function isThreeStageOverlay(item, componentPath, { env = process.env, head = readHead } = {}) {
  if (isScene3dItem(item)) return true
  if (typeof componentPath !== 'string' || componentPath.length === 0) return false
  const stage = env[SCENE3D_STAGE_ENV]
  if (typeof stage === 'string' && stage.length > 0 && resolve(stage) === resolve(componentPath)) return true
  return head(componentPath, HEAD_BYTES)?.startsWith(STAGE_BUNDLE_HEAD) === true
}

/** Where a missing stage is named: the log, never the message (its path can say "scene"). */
const logToStderr = (line) => process.stderr.write(`${line}\n`)

/**
 * The stage the host supplies, or a Scene3dError saying how to get one. The message is the same whether the variable is
 * unset or names a missing file; which of the two, and the path, go to `log` (stderr) for whoever debugs the host.
 */
export function scene3dStage({ env = process.env, exists = existsSync, log = logToStderr } = {}) {
  const stage = env[SCENE3D_STAGE_ENV]
  if (typeof stage !== 'string' || stage.length === 0 || !exists(stage)) {
    log(`[montaj] the 3D stage is unavailable: ${SCENE3D_STAGE_ENV} ${stage ? `names a missing file: ${stage}` : 'is not set'}`)
    throw new Scene3dError('scene3d_stage_unavailable', 'A 3D item needs the 3D stage, and this Montaj has none. Update the Montaj app.')
  }
  return stage
}

/**
 * §673: a close-up camera on one bone or part, in place of the scene's own: one POV shot over all time that rides
 * `follow` ({cast: i, bone} | {cast: i, part}, as the stage's camera shots take it) and looks at it, `distance` metres
 * away, in world axes: in front of a Blender-front cast (-y), a little to one side and above, so a hand is seen from a
 * three-quarter view and the eye never sits on, or straight over, the point it looks at. The stage resolves the ref
 * live, so the bone's place is not needed here.
 */
const CLOSE_UP_DIR = [0.35, -0.9, 0.3]
const CLOSE_UP_SECONDS = 86400
export function closeUpCamera({ follow, distance, lens }, yawDeg = 0) {
  const k = distance / Math.hypot(...CLOSE_UP_DIR)
  // The offset turns with the cast's base `rot` (degrees about +z, as the stage turns a cast), so a cast turned around
  // is still shot from its front. Keyed root turns are the stage's to evaluate; the base rot is what is known here.
  const a = (yawDeg * Math.PI) / 180
  const [x, y, z] = CLOSE_UP_DIR.map((v) => v * k)
  const offset = [x * Math.cos(a) - y * Math.sin(a), x * Math.sin(a) + y * Math.cos(a), z]
  return {
    lens,
    shots: [{ start: 0, end: CLOSE_UP_SECONDS, from: { at: offset, look: [0, 0, 0] }, pov: { follow, offset, frame: 'world' } }],
  }
}

/**
 * look_at's cast in `cast` (the scene's, as the stage numbers it): a number, or a name (an entry's id). -> its index;
 * else a Scene3dError naming the 3D (`lead` leads it, `which` names the 3D).
 */
function castOf(want, cast, lead, which) {
  const n = cast.length, has = `${which} has ${n} cast ${n === 1 ? 'entry' : 'entries'}${n ? ` (0..${n - 1})` : ''}`
  if (typeof want === 'number') {
    if (Number.isInteger(want) && want >= 0 && want < n) return want
    throw new Scene3dError('scene3d_invalid', `${lead} names cast ${want}, and ${has}.`)
  }
  const hits = cast.flatMap((e, k) => (isObj(e) && e.id === want ? [k] : []))
  if (hits.length === 1) return hits[0]
  const ids = cast.flatMap((e) => (isObj(e) && typeof e.id === 'string' ? [e.id] : []))
  const names = ids.length ? `its names: ${[...new Set(ids)].join(', ')}` : 'none of its entries has a name (an id): use the number'
  throw new Scene3dError('scene3d_invalid', `${lead} names cast ${JSON.stringify(want)}, ${hits.length ? `which ${hits.length} entries share` : `which ${which} has no entry named`}; ${names}.`)
}

/** A cut's clock for a scene item (§657): [[item time, scene second, length]], sorted, first at 0, lengths over 0. */
function validTimeMap(map) {
  if (!Array.isArray(map) || map.length === 0) return false
  let end = 0
  for (const [i, p] of map.entries()) {
    if (!Array.isArray(p) || p.length !== 3 || !p.every((x) => typeof x === 'number' && Number.isFinite(x))) return false
    if (p[0] < 0 || p[1] < 0 || p[2] <= 0 || (i === 0 && p[0] > 1e-6) || p[0] < end - 1e-6) return false
    end = p[0] + p[2]
  }
  return true
}


// 3D5: a scene saved by reference. The format is the Montaj app's library/model3d/store.js (this file cannot import it):
// the shot is under `byRef`, with each `meshes` id map of its model and scene as `meshRefs: [id]` and each `textures` map as
// `textureRefs: [id]`; the pieces are files in the project's models/_store folder, which never change once written.
const STORE_ID = /^[0-9a-f]{16}$/
const MOVES_KEY = /^[A-Za-z0-9_-]{1,128}$/
const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v)

/** Fills each `meshRefs` and `textureRefs` list of `v` back into its id map, in the same place among the object's keys. */
function fillRefs(v, piece) {
  if (Array.isArray(v)) return v.map((x) => fillRefs(x, piece))
  if (!isObj(v)) return v
  const o = {}
  for (const [k, x] of Object.entries(v)) {
    if (k === 'meshRefs' && Array.isArray(x)) {
      o.meshes = {}
      for (const id of x) o.meshes[id] = piece('mesh', id)
    } else if (k === 'textureRefs' && Array.isArray(x)) {
      o.textures = {}
      for (const id of x) o.textures[id] = piece('texture', id)
    } else o[k] = fillRefs(x, piece)
  }
  return o
}

/**
 * A by-reference scene's reader: `piece(kind, id)` (a mesh, parsed, or a texture as a data URI) and its move pool. Each store
 * file is read once per call (`files`, by path). A missing or unreadable piece says so in words, with no path in it.
 */
function byRefReader(sceneData, sceneFile, projectDir, fail, { read, readBytes, files }) {
  const R = sceneData.byRef
  const modelsDir = resolve(projectDir, 'models')
  const store = typeof R.store === 'string' && R.store.length > 0 ? resolve(dirname(sceneFile), R.store) : null
  // The store is the project's models/_store, the one folder the app writes pieces to and the stage reads them from.
  if (store === null || store !== join(modelsDir, '_store')) throw fail('invalid', 'keeps its 3D pieces outside the project\'s models/_store folder.')
  // A store folder or piece that is a symlink is refused, like the app's own reader does: it could lead out of the project.
  const link = (path) => { try { return lstatSync(path).isSymbolicLink() } catch { return false } }
  if (link(store) || ['meshes', 'textures', 'moves'].some((d) => link(join(store, d)))) throw fail('invalid', 'has a 3D store that is a link, which is not read.')
  const once = (path, load) => {
    if (!files.has(path)) files.set(path, load(path))
    return files.get(path)
  }
  const gone = (kind, id) => fail('invalid', `is missing part of its 3D (${kind} ${id}). Open the project in Montaj and save that 3D again.`)
  const text = (path) => { try { return link(path) ? null : read(path) } catch { return null } }
  const piece = (kind, id) => {
    if (typeof id !== 'string' || !STORE_ID.test(id)) throw gone(kind, id)
    if (kind === 'mesh') {
      const t = once(join(store, 'meshes', `${id}.json`), text)
      try { if (t !== null) return JSON.parse(t) } catch { /* unreadable: the same error */ }
      throw gone(kind, id)
    }
    for (const [ext, mime] of [['png', 'image/png'], ['jpg', 'image/jpeg']]) {
      const b = once(join(store, 'textures', `${id}.${ext}`), (f) => { try { return link(f) ? null : readBytes(f) } catch { return null } })
      if (b) return `data:${mime};base64,${Buffer.from(b).toString('base64')}`
    }
    throw gone('texture', id)
  }
  if (typeof R.moves !== 'string' || !MOVES_KEY.test(R.moves)) throw gone('move pool', R.moves)
  let moves = null
  try { const t = once(join(store, 'moves', `${R.moves}.json`), text); if (t !== null) moves = JSON.parse(t) } catch { /* the same error */ }
  if (!isObj(moves)) throw gone('move pool', R.moves)
  return { R, piece, moves }
}

/** A by-reference scene as the inline `{slug, model, moves, scene?}` its text would have been. */
function inlineByRef(sceneData, sceneFile, projectDir, fail, io) {
  const { R, piece, moves } = byRefReader(sceneData, sceneFile, projectDir, fail, io)
  return { slug: R.slug, model: fillRefs(R.model, piece), moves, ...(R.scene !== undefined ? { scene: fillRefs(R.scene, piece) } : {}) }
}

// §773: a scene whose meshes and textures are given once. Filled per cast entry, 100 entries of one tree carried its meshes and
// textures 100 times (about 680 MB for a library tree, past V8's 512 MB string limit: sample_too_large). Packed, it is the
// Montaj app's store.js packPieces shape (this file cannot import it), pieces first:
//   {pieces: {v: 1, meshes: {id: mesh}, textures: {id: data URI}}, slug, model, moves, scene?}
// with each id map in model and scene left as its ids in place (meshRefs, textureRefs, as a by-reference scene has them). The
// stage fills them back, one object per id. Only for a stage whose header says it can (stageTakesPieces).
const PIECES_V = 1
export const PIECES_HEAD = `{"pieces":{"v":${PIECES_V},`
const PIECE_ID = /^[0-9a-f]{16}$/
const pieceMap = (m) => isObj(m) && Object.keys(m).length > 0 && Object.keys(m).every((k) => PIECE_ID.test(k))
const own = (o, k) => Object.prototype.hasOwnProperty.call(o, k)

/** Every meshRefs and textureRefs id under `v`, into the sets. */
function collectRefs(v, meshes, textures) {
  if (Array.isArray(v)) { for (const x of v) collectRefs(x, meshes, textures); return }
  if (!isObj(v)) return
  for (const [k, x] of Object.entries(v)) {
    if (k === 'meshRefs' && Array.isArray(x)) for (const id of x) meshes.add(id)
    else if (k === 'textureRefs' && Array.isArray(x)) for (const id of x) textures.add(id)
    else collectRefs(x, meshes, textures)
  }
}

/** A by-reference scene packed: its refs left in place, each piece read from the store once. */
function packByRef(sceneData, sceneFile, projectDir, fail, io) {
  const { R, piece, moves } = byRefReader(sceneData, sceneFile, projectDir, fail, io)
  const meshes = new Set(), textures = new Set()
  collectRefs(R.model, meshes, textures)
  collectRefs(R.scene, meshes, textures)
  const pieces = { v: PIECES_V, meshes: {}, textures: {} }
  for (const id of meshes) pieces.meshes[id] = piece('mesh', id)
  for (const id of textures) pieces.textures[id] = piece('texture', id)
  return { pieces, slug: R.slug, model: R.model, moves, ...(R.scene !== undefined ? { scene: R.scene } : {}) }
}

/** `v` with each id map of meshes or textures as its ids in place, each id's data into `out` once; `out.repeats` counts a map
 *  naming an id already taken (the app's store.js strip). */
function stripPieces(v, out) {
  if (Array.isArray(v)) return v.map((x) => stripPieces(x, out))
  if (!isObj(v)) return v
  const o = {}
  for (const [k, x] of Object.entries(v)) {
    const tex = k === 'textures' && pieceMap(x) && Object.values(x).every((u) => typeof u === 'string')
    if ((k === 'meshes' && pieceMap(x)) || tex) {
      const into = tex ? out.textures : out.meshes
      for (const id of Object.keys(x)) { if (own(into, id)) out.repeats++; else into[id] = x[id] }
      o[tex ? 'textureRefs' : 'meshRefs'] = Object.keys(x)
    } else o[k] = stripPieces(x, out)
  }
  return o
}

/** An inline scene packed, and how many of its maps repeated a piece (0: packing saves nothing). */
function packInline(sceneData) {
  const out = { meshes: {}, textures: {}, repeats: 0 }
  const model = stripPieces(sceneData.model, out)
  const scene = isObj(sceneData.scene) ? stripPieces(sceneData.scene, out) : sceneData.scene
  // model and scene keep their places among the keys (a spread then the same key keeps its place)
  return { packed: { pieces: { v: PIECES_V, meshes: out.meshes, textures: out.textures }, ...sceneData, model, ...(sceneData.scene !== undefined ? { scene } : {}) }, repeats: out.repeats }
}

const piecesByStage = new Map()
/**
 * Whether the stage fills a packed scene: its header (the first three lines) says "SCENE_PIECES v1" (the Montaj app's scene
 * stage from engine 46). Read once per stage file and version. An unreadable stage is no.
 */
export function stageTakesPieces(stage) {
  let key
  try { const st = statSync(stage); key = `${stage}:${st.size}:${st.mtimeMs}` } catch { return false }
  if (piecesByStage.has(key)) return piecesByStage.get(key)
  let head = ''
  try {
    const fd = openSync(stage, 'r')
    try { const b = Buffer.alloc(8192); head = b.subarray(0, readSync(fd, b, 0, b.length, 0)).toString('utf8') } finally { closeSync(fd) }
  } catch { head = '' }
  const yes = /SCENE_PIECES v1\b/.test(head.split('\n').slice(0, 3).join('\n'))
  piecesByStage.set(key, yes)
  return yes
}

const readText = (f) => readFileSync(f, 'utf8')
const readBytesDefault = (f) => readFileSync(f)

/**
 * Each scene file's text as handed to the stage, by its path: `{ stamp, sceneJson }`, the stamp being the file's inode, size
 * and mtime. A by-reference scene inlines to tens of MB (GPS, 2026-11-13: 34 items, 8.8 to 113 MB each, 1.4 GB in all), and
 * render.js materializes its project twice (the render, then loudness's own load), so without this the second pass parsed
 * every mesh again and held a second copy of every text, and the render ran out of V8 heap. A hit hands back the very
 * same string. Only for the default reader on a real file, and never for a close-up (its text is its own).
 */
const sceneTexts = new Map()

/** 3D39: the bake key of a scene file's text: the first 32 hex characters of the sha256 of its bytes (UTF-8). */
export function sceneBakeKey(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex').slice(0, 32)
}

/** Where the bake for a scene file of key `key` is: `bake/<key>.mjbk` beside the file. */
export const bakeFileOf = (sceneFile, key) => join(dirname(sceneFile), 'bake', `${key}.mjbk`)

/** Each bake's base64 by its path, `{ stamp, b64 }`, so render.js's second pass hands the same string (as sceneTexts). */
const bakeTexts = new Map()

/**
 * The bake for a scene file of key `key` as base64, or null when there is none (keyed motion, never an error). A bake or
 * bake folder that is a link is not read, like the store. An unreadable one is a log line.
 */
function physicsBakeOf(sceneFile, key, { exists, readBytes, log }) {
  const dir = join(dirname(sceneFile), 'bake'), file = bakeFileOf(sceneFile, key)
  if (!exists(file)) return null
  const link = (path) => { try { return lstatSync(path).isSymbolicLink() } catch { return false } }
  if (link(dir) || link(file)) { log(`[montaj] a 3D's physics bake is a link, not read: ${file}`); return null }
  const stamp = readBytes === readBytesDefault ? sceneStamp(file) : null
  const known = stamp !== null ? bakeTexts.get(file) : undefined
  if (known && known.stamp === stamp) return known.b64
  let b64
  try {
    b64 = Buffer.from(readBytes(file)).toString('base64')
  } catch (e) {
    log(`[montaj] a 3D's physics bake cannot be read (${e && e.code ? e.code : e}): ${file}`)
    return null
  }
  if (b64.length === 0) return null
  if (stamp !== null) bakeTexts.set(file, { stamp, b64 })
  return b64
}

function sceneStamp(sceneFile) {
  try {
    const st = statSync(sceneFile)
    return `${st.ino}:${st.size}:${st.mtimeMs}`
  } catch {
    return null
  }
}

/**
 * Rewrites every scene item of `project` into a plain overlay item. `projectDir` is the folder holding project.json.
 * Throws Scene3dError (`scene3d_stage_unavailable`, `scene3d_scene_missing`, `scene3d_invalid`) naming the item.
 * Returns how many items it rewrote.
 *
 * The messages reach whoever exports, so they say "3D" and never "scene": the user never meets that concept (§308).
 * The codes keep their names; they are for the host and the AI.
 *
 * `only` (§651) picks the scene items to rewrite; the rest stay `engine:scene3d`, unread. A sampled frame passes the
 * items on screen at its time: each scene's text is inlined whole (a real one is 25 to 33 MB), so materializing a
 * project of 24 scenes held 620 MB of text, and the sample's JSON copy of it passed V8's 512 MB string limit.
 *
 * `closeUp` (§673, a sample's look_at: {follow, distance, lens}) replaces each rewritten scene's camera with
 * closeUpCamera, in the text handed to the stage only; the scene's file is not touched.
 *
 * §773: for a stage that fills a packed scene (stageTakesPieces; `pieces` true or false decides instead), a by-reference scene
 * is handed over packed (each mesh and texture once) and an inline one is packed when a piece repeats in it.
 *
 * 3D39: `physicsBake` (base64) joins the props when the scene file's bake exists (physicsBakeOf); a prop of that name the
 * item already had is dropped, so the bake is always the file's.
 */
export function materializeScene3d(project, projectDir, { env = process.env, exists = existsSync, read = readText, readBytes = readBytesDefault, log = logToStderr, only = null, closeUp = null, pieces = null } = {}) {
  let n = 0
  const files = new Map()
  const packs = new Map() // a stage path: whether its stage fills a packed scene
  for (const track of trackItems(project)) {
    for (const item of track ?? []) {
      if (!isScene3dItem(item)) continue
      if (only && !only(item)) continue
      const label = item.id ? `3D item "${item.id}"` : 'A 3D item'
      if (typeof projectDir !== 'string' || projectDir.length === 0) {
        throw new Scene3dError('scene3d_invalid', `${label} needs the project's folder to find its 3D.`)
      }
      const { physicsBake: _stale, ...props } = item.props && typeof item.props === 'object' && !Array.isArray(item.props) ? item.props : {}
      const name = props.scene
      if (name !== undefined && (typeof name !== 'string' || !SCENE_NAME.test(name))) {
        throw new Scene3dError('scene3d_invalid', `${label}: its 3D must be named with lowercase letters, digits and - (got ${JSON.stringify(name)}).`)
      }
      const which = name === undefined ? 'the project\'s own 3D' : `its 3D "${name}"`
      const inPoint = props.inPoint === undefined ? 0 : props.inPoint
      if (typeof inPoint !== 'number' || !Number.isFinite(inPoint) || inPoint < 0) {
        throw new Scene3dError('scene3d_invalid', `${label}: inPoint must be 0 or more seconds (got ${JSON.stringify(props.inPoint)}).`)
      }
      if (props.timeMap !== undefined && !validTimeMap(props.timeMap)) {
        throw new Scene3dError('scene3d_invalid', `${label}: timeMap is [[item time, scene second, length]] pieces in order, the first at item time 0 (got ${JSON.stringify(props.timeMap)}).`)
      }
      const stage = scene3dStage({ env, exists, log })
      if (!packs.has(stage)) packs.set(stage, pieces === null ? stageTakesPieces(stage) : pieces === true)
      const pack = packs.get(stage)
      const sceneFile = name === undefined ? join(projectDir, 'models', 'active.json') : join(projectDir, 'models', 'scenes', name, 'active.json')
      if (!exists(sceneFile)) {
        throw new Scene3dError('scene3d_scene_missing', `${label}: ${which} is not saved yet.`)
      }
      const stamp = read === readText && !closeUp ? sceneStamp(sceneFile) : null
      const known = stamp !== null ? sceneTexts.get(sceneFile) : undefined
      const withBake = (key) => {
        const physicsBake = physicsBakeOf(sceneFile, key, { exists, readBytes, log })
        return physicsBake === null ? {} : { physicsBake }
      }
      if (known && known.stamp === stamp && known.pack === pack) {
        item.src = stage
        item.props = { ...props, sceneFile, sceneJson: known.sceneJson, inPoint, ...withBake(known.bakeKey) }
        n += 1
        continue
      }
      let sceneJson, sceneData, bakeKey
      try {
        sceneJson = read(sceneFile)
        bakeKey = sceneBakeKey(sceneJson)
        sceneData = JSON.parse(sceneJson)
      } catch (e) {
        // A read error's code, not its message: the message carries the file's path, which names the scenes folder.
        const why = e && typeof e.code === 'string' ? e.code : (e && e.message ? e.message : e)
        throw new Scene3dError('scene3d_invalid', `${label}: ${which} cannot be read (${why}).`)
      }
      if (isObj(sceneData) && isObj(sceneData.byRef) && sceneData.byRef.v === 1) {
        const fail = (_, why) => new Scene3dError('scene3d_invalid', `${label}: ${which} ${why}`)
        sceneData = (pack ? packByRef : inlineByRef)(sceneData, sceneFile, projectDir, fail, { read, readBytes, files })
        sceneJson = JSON.stringify(sceneData)
      } else if (pack && isObj(sceneData) && isObj(sceneData.model)) {
        const { packed, repeats } = packInline(sceneData)
        if (repeats > 0) { sceneData = packed; sceneJson = JSON.stringify(packed) }
      }
      if (!sceneData || typeof sceneData !== 'object' || Array.isArray(sceneData) || !sceneData.model || typeof sceneData.model !== 'object') {
        throw new Scene3dError('scene3d_invalid', `${label}: ${which} has no model in it.`)
      }
      if (closeUp) {
        // The scene the stage plays is the file's `scene` ({slug, model, moves, scene}, a by-reference one inlined above): its
        // cast is the one the stage numbers, a shot's set entries first. Its camera is the one replaced.
        const scene = isObj(sceneData.scene) ? sceneData.scene : {}
        const cast = Array.isArray(scene.cast) ? scene.cast : []
        const i = castOf(closeUp.follow.cast, cast, `${label}: look_at`, which)
        const rot = cast[i]?.rot
        const follow = { ...closeUp.follow, cast: i }
        sceneJson = JSON.stringify({ ...sceneData, scene: { ...scene, camera: closeUpCamera({ ...closeUp, follow }, typeof rot === 'number' && Number.isFinite(rot) ? rot : 0) } })
      }
      if (stamp !== null) sceneTexts.set(sceneFile, { stamp, pack, sceneJson, bakeKey })
      item.src = stage
      item.props = { ...props, sceneFile, sceneJson, inPoint, ...withBake(bakeKey) }
      n += 1
    }
  }
  return n
}

/**
 * structuredClone(project), each scene item's `sceneJson` in the copy being the original's own string. structuredClone
 * copies every string, and a materialized project's scene text is most of its size (sceneTexts above), so render.js's
 * pristine copy doubled it.
 */
export function cloneSharingSceneText(project) {
  const texts = []
  for (const [t, track] of trackItems(project).entries()) {
    for (const [i, item] of (track ?? []).entries()) {
      if (isObj(item) && isObj(item.props) && typeof item.props.sceneJson === 'string') {
        texts.push([t, i, item.props, item.props.sceneJson])
        item.props.sceneJson = ''
      }
    }
  }
  let copy
  try {
    copy = structuredClone(project)
  } finally {
    for (const [, , props, text] of texts) props.sceneJson = text
  }
  const tracks = trackItems(copy)
  for (const [t, i, , text] of texts) tracks[t][i].props.sceneJson = text
  return copy
}
