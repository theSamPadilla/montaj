/**
 * scene3d.js (§239): a 3D scene item is an overlay item whose `src` is the reserved `engine:scene3d`:
 *
 *   { "type": "overlay", "src": "engine:scene3d", "start": 12, "end": 16.5,
 *     "props": { "scene": "hands", "inPoint": 2 } }
 *
 * `materializeScene3d` turns each one into the plain overlay every other part of the render already knows, in
 * place and before anything else reads the project: `src` becomes the stage the HOST supplies
 * (`MONTAJ_SCENE3D_STAGE`, an absolute path to a stage .jsx: the app keeps the freshest one in its runtime home),
 * and `props` gain `sceneFile` (the scene's active.json, an absolute path: it travels to the page as a file URL and is
 * what the sample cache's manifest records), `sceneJson` (that file's text, read and checked here, so the stage draws from
 * the page's first render and an unreadable scene fails the render instead of drawing blank; one string, so the
 * props scanners (path rewriting, the read boundary, named URLs) see one value and not every string of the scene) and `inPoint` (seconds
 * into the scene's own timeline). From then on the bundle, the read boundary,
 * the sample cache's input manifest (it records props file paths, so an edited scene misses) and the segment encoder
 * need to know nothing about scenes.
 *
 * `scene` names a folder under `<project>/models/scenes/<name>/`; absent is the project's single scene,
 * `<project>/models/active.json` (what the model-3d template's overlay copy imports today). A missing stage or scene
 * is an error that names it, never a blank frame. A second pass finds nothing left to do.
 */
import { closeSync, existsSync, openSync, readFileSync, readSync } from 'fs'
import { dirname, join, relative, resolve, isAbsolute } from 'path'
import { trackItems } from './project-tracks.js'

export const SCENE3D_SRC = 'engine:scene3d'
export const SCENE3D_STAGE_ENV = 'MONTAJ_SCENE3D_STAGE'
// The same rule save_model and the preview use (a folder made by hand with any other name would export and not preview).
const SCENE_NAME = /^[a-z0-9][a-z0-9-]{0,47}$/

/** An error with a stable `code`, for the CLI's JSON failure line. */
export class Scene3dError extends Error {
  constructor(code, message) {
    super(message)
    this.code = code
  }
}

export const isScene3dItem = (item) => !!item && item.type === 'overlay' && item.src === SCENE3D_SRC

/**
 * The first line of every 3D stage the app generates (its build-model3d-stage.mjs): the stage of a scene item, and the
 * per-project stage an older project placed as a plain overlay (`overlays/model3d_stage.jsx` and its kin).
 */
export const STAGE_BUNDLE_HEAD = '// GENERATED by library/scripts/build-model3d-stage.mjs'
// The head is all that is read: a stage is about 200 KB.
const HEAD_BYTES = 300

/** The first `bytes` of a file as text, or null when it cannot be read. */
function readHead(path, bytes) {
  let fd
  try {
    fd = openSync(path, 'r')
    const buf = Buffer.alloc(bytes)
    return buf.toString('utf8', 0, readSync(fd, buf, 0, bytes, 0))
  } catch {
    return null
  } finally {
    if (fd !== undefined) closeSync(fd)
  }
}

/**
 * Whether an overlay item draws a 3D stage (§377): a scene item (`engine:scene3d`), before or after
 * materializeScene3d points it at the host's stage (`componentPath` is then that stage), or an overlay whose source is
 * a generated stage (STAGE_BUNDLE_HEAD), as an older project's per-project stage is. Its render spec carries
 * `scene3d: true`, and its motion blur is averaged in the page (renderer.js blursInPage). A source that is missing or
 * cannot be read is not a stage.
 *
 * @param {object} item
 * @param {string} componentPath  the overlay's source, as render.js resolves it
 */
export function isThreeStageOverlay(item, componentPath, { env = process.env, head = readHead } = {}) {
  if (isScene3dItem(item)) return true
  if (typeof componentPath !== 'string' || componentPath.length === 0) return false
  const stage = env[SCENE3D_STAGE_ENV]
  if (typeof stage === 'string' && stage.length > 0 && resolve(stage) === resolve(componentPath)) return true
  return head(componentPath, HEAD_BYTES)?.startsWith(STAGE_BUNDLE_HEAD) === true
}

/** Where a missing stage is named: the log, never the message (its path can say "scene"). */
const logToStderr = (line) => process.stderr.write(`${line}\n`)

/**
 * The stage the host supplies, or a Scene3dError saying how to get one. The message is the same whether the variable is
 * unset or names a missing file; which of the two, and the path, go to `log` (stderr) for whoever debugs the host.
 */
export function scene3dStage({ env = process.env, exists = existsSync, log = logToStderr } = {}) {
  const stage = env[SCENE3D_STAGE_ENV]
  if (typeof stage !== 'string' || stage.length === 0 || !exists(stage)) {
    log(`[montaj] the 3D stage is unavailable: ${SCENE3D_STAGE_ENV} ${stage ? `names a missing file: ${stage}` : 'is not set'}`)
    throw new Scene3dError('scene3d_stage_unavailable', 'A 3D item needs the 3D stage, and this Montaj has none. Update the Montaj app.')
  }
  return stage
}

/**
 * §673: a close-up camera on one bone or part, in place of the scene's own: one POV shot over all time that rides
 * `follow` ({cast: i, bone} | {cast: i, part}, as the stage's camera shots take it) and looks at it, `distance` metres
 * away, in world axes: in front of a Blender-front cast (-y), a little to one side and above, so a hand is seen from a
 * three-quarter view and the eye never sits on, or straight over, the point it looks at. The stage resolves the ref
 * live, so the bone's place is not needed here.
 */
const CLOSE_UP_DIR = [0.35, -0.9, 0.3]
const CLOSE_UP_SECONDS = 86400
export function closeUpCamera({ follow, distance, lens }, yawDeg = 0) {
  const k = distance / Math.hypot(...CLOSE_UP_DIR)
  // The offset turns with the cast's base `rot` (degrees about +z, as the stage turns a cast), so a cast turned around
  // is still shot from its front. Keyed root turns are the stage's to evaluate; the base rot is what is known here.
  const a = (yawDeg * Math.PI) / 180
  const [x, y, z] = CLOSE_UP_DIR.map((v) => v * k)
  const offset = [x * Math.cos(a) - y * Math.sin(a), x * Math.sin(a) + y * Math.cos(a), z]
  return {
    lens,
    shots: [{ start: 0, end: CLOSE_UP_SECONDS, from: { at: offset, look: [0, 0, 0] }, pov: { follow, offset, frame: 'world' } }],
  }
}

/** A cut's clock for a scene item (§657): [[item time, scene second, length]], sorted, first at 0, lengths over 0. */
function validTimeMap(map) {
  if (!Array.isArray(map) || map.length === 0) return false
  let end = 0
  for (const [i, p] of map.entries()) {
    if (!Array.isArray(p) || p.length !== 3 || !p.every((x) => typeof x === 'number' && Number.isFinite(x))) return false
    if (p[0] < 0 || p[1] < 0 || p[2] <= 0 || (i === 0 && p[0] > 1e-6) || p[0] < end - 1e-6) return false
    end = p[0] + p[2]
  }
  return true
}


// 3D5: a scene saved by reference. The format is the Montaj app's library/model3d/store.js (this file cannot import it):
// the shot is under `byRef`, with each `meshes` id map of its model and scene as `meshRefs: [id]` and each `textures` map as
// `textureRefs: [id]`; the pieces are files in the project's models/_store folder, which never change once written.
const STORE_ID = /^[0-9a-f]{16}$/
const MOVES_KEY = /^[A-Za-z0-9_-]{1,128}$/
const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v)

/** Fills each `meshRefs` and `textureRefs` list of `v` back into its id map, in the same place among the object's keys. */
function fillRefs(v, piece) {
  if (Array.isArray(v)) return v.map((x) => fillRefs(x, piece))
  if (!isObj(v)) return v
  const o = {}
  for (const [k, x] of Object.entries(v)) {
    if (k === 'meshRefs' && Array.isArray(x)) {
      o.meshes = {}
      for (const id of x) o.meshes[id] = piece('mesh', id)
    } else if (k === 'textureRefs' && Array.isArray(x)) {
      o.textures = {}
      for (const id of x) o.textures[id] = piece('texture', id)
    } else o[k] = fillRefs(x, piece)
  }
  return o
}

/**
 * A by-reference scene as the inline `{slug, model, moves, scene?}` its text would have been. Each store file is read once
 * per call (`files`, by path). A missing or unreadable piece says so in words, with no path in it.
 */
function inlineByRef(sceneData, sceneFile, projectDir, fail, { read, readBytes, files }) {
  const R = sceneData.byRef
  const modelsDir = resolve(projectDir, 'models')
  const store = typeof R.store === 'string' && R.store.length > 0 ? resolve(dirname(sceneFile), R.store) : null
  const inside = store !== null && relative(modelsDir, store) !== '' && !relative(modelsDir, store).startsWith('..') && !isAbsolute(relative(modelsDir, store))
  if (!inside) throw fail('invalid', 'its 3D points outside the project\'s models folder.')
  const once = (path, load) => {
    if (!files.has(path)) files.set(path, load(path))
    return files.get(path)
  }
  const gone = (kind, id) => fail('invalid', `is missing part of its 3D (${kind} ${id}). Open the project in Montaj and save that 3D again.`)
  const text = (path) => { try { return read(path) } catch { return null } }
  const piece = (kind, id) => {
    if (typeof id !== 'string' || !STORE_ID.test(id)) throw gone(kind, id)
    if (kind === 'mesh') {
      const t = once(join(store, 'meshes', `${id}.json`), text)
      try { if (t !== null) return JSON.parse(t) } catch { /* unreadable: the same error */ }
      throw gone(kind, id)
    }
    for (const [ext, mime] of [['png', 'image/png'], ['jpg', 'image/jpeg']]) {
      const b = once(join(store, 'textures', `${id}.${ext}`), (f) => { try { return readBytes(f) } catch { return null } })
      if (b) return `data:${mime};base64,${Buffer.from(b).toString('base64')}`
    }
    throw gone('texture', id)
  }
  if (typeof R.moves !== 'string' || !MOVES_KEY.test(R.moves)) throw gone('move pool', R.moves)
  let moves = null
  try { const t = once(join(store, 'moves', `${R.moves}.json`), text); if (t !== null) moves = JSON.parse(t) } catch { /* the same error */ }
  if (!isObj(moves)) throw gone('move pool', R.moves)
  return { slug: sceneData.slug, model: fillRefs(R.model, piece), moves, ...(R.scene !== undefined ? { scene: fillRefs(R.scene, piece) } : {}) }
}

/**
 * Rewrites every scene item of `project` into a plain overlay item. `projectDir` is the folder holding project.json.
 * Throws Scene3dError (`scene3d_stage_unavailable`, `scene3d_scene_missing`, `scene3d_invalid`) naming the item.
 * Returns how many items it rewrote.
 *
 * The messages reach whoever exports, so they say "3D" and never "scene": the user never meets that concept (§308).
 * The codes keep their names; they are for the host and the AI.
 *
 * `only` (§651) picks the scene items to rewrite; the rest stay `engine:scene3d`, unread. A sampled frame passes the
 * items on screen at its time: each scene's text is inlined whole (a real one is 25 to 33 MB), so materializing a
 * project of 24 scenes held 620 MB of text, and the sample's JSON copy of it passed V8's 512 MB string limit.
 *
 * `closeUp` (§673, a sample's look_at: {follow, distance, lens}) replaces each rewritten scene's camera with
 * closeUpCamera, in the text handed to the stage only; the scene's file is not touched.
 */
export function materializeScene3d(project, projectDir, { env = process.env, exists = existsSync, read = (f) => readFileSync(f, 'utf8'), readBytes = (f) => readFileSync(f), log = logToStderr, only = null, closeUp = null } = {}) {
  let n = 0
  const files = new Map()
  for (const track of trackItems(project)) {
    for (const item of track ?? []) {
      if (!isScene3dItem(item)) continue
      if (only && !only(item)) continue
      const label = item.id ? `3D item "${item.id}"` : 'A 3D item'
      if (typeof projectDir !== 'string' || projectDir.length === 0) {
        throw new Scene3dError('scene3d_invalid', `${label} needs the project's folder to find its 3D.`)
      }
      const props = item.props && typeof item.props === 'object' && !Array.isArray(item.props) ? item.props : {}
      const name = props.scene
      if (name !== undefined && (typeof name !== 'string' || !SCENE_NAME.test(name))) {
        throw new Scene3dError('scene3d_invalid', `${label}: its 3D must be named with lowercase letters, digits and - (got ${JSON.stringify(name)}).`)
      }
      const which = name === undefined ? 'the project\'s own 3D' : `its 3D "${name}"`
      const inPoint = props.inPoint === undefined ? 0 : props.inPoint
      if (typeof inPoint !== 'number' || !Number.isFinite(inPoint) || inPoint < 0) {
        throw new Scene3dError('scene3d_invalid', `${label}: inPoint must be 0 or more seconds (got ${JSON.stringify(props.inPoint)}).`)
      }
      if (props.timeMap !== undefined && !validTimeMap(props.timeMap)) {
        throw new Scene3dError('scene3d_invalid', `${label}: timeMap is [[item time, scene second, length]] pieces in order, the first at item time 0 (got ${JSON.stringify(props.timeMap)}).`)
      }
      const stage = scene3dStage({ env, exists, log })
      const sceneFile = name === undefined ? join(projectDir, 'models', 'active.json') : join(projectDir, 'models', 'scenes', name, 'active.json')
      if (!exists(sceneFile)) {
        throw new Scene3dError('scene3d_scene_missing', `${label}: ${which} is not saved yet.`)
      }
      let sceneJson, sceneData
      try {
        sceneJson = read(sceneFile)
        sceneData = JSON.parse(sceneJson)
      } catch (e) {
        // A read error's code, not its message: the message carries the file's path, which names the scenes folder.
        const why = e && typeof e.code === 'string' ? e.code : (e && e.message ? e.message : e)
        throw new Scene3dError('scene3d_invalid', `${label}: ${which} cannot be read (${why}).`)
      }
      if (isObj(sceneData) && isObj(sceneData.byRef) && sceneData.byRef.v === 1) {
        const fail = (_, why) => new Scene3dError('scene3d_invalid', `${label}: ${which} ${why}`)
        sceneData = inlineByRef(sceneData, sceneFile, projectDir, fail, { read, readBytes, files })
        sceneJson = JSON.stringify(sceneData)
      }
      if (!sceneData || typeof sceneData !== 'object' || Array.isArray(sceneData) || !sceneData.model || typeof sceneData.model !== 'object') {
        throw new Scene3dError('scene3d_invalid', `${label}: ${which} has no model in it.`)
      }
      if (closeUp) {
        const cast = Array.isArray(sceneData.cast) ? sceneData.cast : []
        if (!(closeUp.follow.cast < cast.length)) {
          throw new Scene3dError('scene3d_invalid', `${label}: look_at names cast ${closeUp.follow.cast}, and ${which} has ${cast.length} cast ${cast.length === 1 ? 'entry' : 'entries'}${cast.length ? ` (0..${cast.length - 1})` : ''}.`)
        }
        const rot = cast[closeUp.follow.cast]?.rot
        sceneJson = JSON.stringify({ ...sceneData, camera: closeUpCamera(closeUp, typeof rot === 'number' && Number.isFinite(rot) ? rot : 0) })
      }
      item.src = stage
      item.props = { ...props, sceneFile, sceneJson, inPoint }
      n += 1
    }
  }
  return n
}
